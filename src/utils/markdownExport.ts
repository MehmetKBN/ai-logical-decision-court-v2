import { DELIBERATION_ORDER, HATS } from '../config/hats';
import type { CourtSession } from '../types/court';

/**
 * Formats a complete or partial Decision Court session into a clean,
 * publication-ready Markdown transcript.
 */
export function formatCourtTranscriptMarkdown(
  session: CourtSession,
  modelLabel: string,
): string {
  const timestamp = new Date().toISOString().replace('T', ' ').slice(0, 19);
  const lines: string[] = [
    '# AI Logical Decision Court v2 — Official Case Transcript',
    '',
    `- **Generated At:** ${timestamp} UTC`,
    `- **AI Engine / Model:** ${modelLabel}`,
    `- **Session Status:** ${session.status.toUpperCase()}`,
    '',
    '---',
    '',
    '## Case Dilemma',
    '',
    session.casePrompt.trim() || '_No case prompt recorded._',
    '',
  ];

  if (session.contextConstraints.trim().length > 0) {
    lines.push(
      '### Context & Constraints',
      '',
      session.contextConstraints.trim(),
      '',
    );
  }

  lines.push('---', '');

  for (const hatId of DELIBERATION_ORDER) {
    const hat = HATS[hatId];
    const response = session.responses[hatId];
    const content = response.content.trim();

    if (!content && response.status !== 'error') {
      continue;
    }

    const headingPrefix = hat.isJudge
      ? `## ${hat.turnOrder}. ${hat.name} — Final Verdict & Action Plan (${hat.roleTitle})`
      : `## ${hat.turnOrder}. ${hat.name} — ${hat.roleTitle}`;

    lines.push(headingPrefix);
    lines.push(`*Cognitive Lens: ${hat.cognitiveLens}*`);
    lines.push('');

    if (response.status === 'error') {
      lines.push(
        `> **Error During Turn:** ${response.errorMessage ?? 'Deliberation interrupted.'}`,
        '',
      );
    } else {
      lines.push(content, '');
    }

    lines.push('---', '');
  }

  lines.push(
    '*Generated by AI Logical Decision Court v2 (Edward De Bono\'s Six Thinking Hats Methodology)*',
    '',
  );

  return lines.join('\n');
}

/**
 * Triggers a clean browser file download for a Markdown transcript string.
 */
export function downloadMarkdownFile(
  content: string,
  filename = 'decision-court-verdict.md',
): void {
  if (typeof window === 'undefined' || typeof document === 'undefined') {
    return;
  }

  const blob = new Blob([content], { type: 'text/markdown;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const anchor = document.createElement('a');
  anchor.href = url;
  anchor.download = filename;
  document.body.appendChild(anchor);
  anchor.click();
  document.body.removeChild(anchor);
  URL.revokeObjectURL(url);
}
